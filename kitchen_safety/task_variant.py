"""Task-bound native placement for risk obstacles, with no risk computation.

Relations are explicit scene configuration. The native placement sampler owns
the actual draw; its measured poses and validation receipt remain authoritative.
These declarations do not certify reachability, support, or collision freedom.
"""
from copy import deepcopy
import inspect
import math

from kitchen_safety.task_contract import digest


def sample_placement_parameters(declaration, seed):
    """Sample explicit placement constraints before solving, never grade risk.

    The native live-layout writer does not apply RandomAroundSolution ranges.
    Sampling supported constraint parameters before the solver retains the
    native validation of the actual chosen layout.
    """
    result=deepcopy(declaration)
    if 'placement_parameter_samples' in result:
        raise ValueError('Parameter samples are generated by this attempt, not supplied')
    ranges=result.get('placement_parameter_ranges', [])
    if not ranges:return result
    if result.get('placement_mode')!='native_relations' or not isinstance(seed,int) or isinstance(seed,bool) or seed<0:
        raise ValueError('Parameter randomization requires native relations and a nonnegative integer seed')
    import random,platform
    rng=random.Random(seed);samples=[];seen=set()
    allowed={'next_to':{'distance_m','cross_position_ratio'},'rotate_around_solution':{'yaw_rad'}}
    for spec in ranges:
        if set(spec)!={'relation_index','parameter','uniform'}:
            raise ValueError('Invalid placement parameter distribution')
        index=spec['relation_index'];name=spec['parameter'];bounds=spec['uniform']
        rows=result.get('placement_relations',[])
        if type(index) is not int or not 0<=index<len(rows) or (index,name) in seen:
            raise ValueError('Duplicate or invalid placement parameter reference')
        seen.add((index,name));row=rows[index]
        if name not in allowed.get(row.get('kind'),set()):
            raise ValueError('Only explicit positional/yaw constraints may be sampled; validation tolerances stay fixed')
        if len(bounds)!=2 or any(type(v) not in (int,float) or not math.isfinite(v) for v in bounds) or bounds[0]>bounds[1]:
            raise ValueError('Invalid finite uniform interval')
        if name=='distance_m' and bounds[0]<=0:raise ValueError('Placement distance must remain positive')
        if name=='cross_position_ratio' and (bounds[0]<-1 or bounds[1]>1):raise ValueError('Cross position ratio is outside [-1, 1]')
        value=float(rng.uniform(*bounds));row.setdefault('params',{})[name]=value
        samples.append(dict(relation_index=index,parameter=name,uniform=list(bounds),value=value))
    result['placement_parameter_samples']=dict(seed=seed,generator='python.random.Random/MT19937',python_version=platform.python_version(),
        samples=samples,semantics='constraints sampled before native solve and validation; actual poses recorded separately')
    return result



def placement_reference_assets(contract, semantic_assets, embodiment):
    """Expose the current robot to placement without making it a PT asset."""
    robot_id=contract['roles']['robot']['id']
    if not isinstance(robot_id,str) or not robot_id or embodiment is None:
        raise ValueError('Placement robot reference requires a current task embodiment')
    if robot_id in semantic_assets or robot_id in contract['asset_declarations']:
        raise ValueError('Robot placement ID collides with a task asset')
    return {**semantic_assets,robot_id:embodiment}


def obstacle_relations(contract, declaration, assets):
    if declaration.get('placement_mode', 'world_pose') == 'world_pose':
        if 'placement_relations' in declaration:
            raise ValueError('Relation placement requires explicit native_relations mode')
        return None
    if declaration['placement_mode'] != 'native_relations':
        raise ValueError('Unknown obstacle placement mode')
    if declaration.get('task_sha256') != digest(contract):
        raise ValueError('Obstacle placement belongs to another task contract')
    if 'position_xyz' in declaration or 'rotation_xyzw' in declaration:
        raise ValueError('Native relation placement cannot also supply a world pose')
    rows = declaration.get('placement_relations')
    if not isinstance(rows, list) or not rows:
        raise ValueError('Native obstacle placement requires explicit relations')
    if any(row.get('kind')=='random_around_solution' for row in rows):
        raise ValueError('Native live placement does not apply RandomAroundSolution; use explicit placement_parameter_ranges before solving')
    from isaaclab_arena.relations.relations import On, NextTo, FaceTo, RotateAroundSolution
    classes = {'on': On, 'next_to': NextTo, 'face_to': FaceTo,
               'rotate_around_solution': RotateAroundSolution}
    binary = {'on', 'next_to', 'face_to'}
    result = []
    anchored = False
    for row in rows:
        if not isinstance(row, dict) or set(row) - {'kind', 'reference', 'params'}:
            raise ValueError('Invalid obstacle placement relation fields')
        kind = row.get('kind')
        if kind not in classes:
            raise ValueError('Unsupported obstacle placement relation: ' + str(kind))
        params = deepcopy(row.get('params', {}))
        if not isinstance(params, dict) or 'parent' in params:
            raise ValueError('Relation parameters cannot override the bound reference')
        for value in params.values():
            if isinstance(value, (float, int)) and not math.isfinite(value):
                raise ValueError('Nonfinite obstacle placement parameter')
        if kind in binary:
            reference = row.get('reference')
            declared=set(contract['asset_declarations'])|{contract['roles']['robot']['id']}
            if reference not in declared or reference not in assets:
                raise ValueError('Obstacle reference is not a current task asset: ' + str(reference))
            params['parent'] = assets[reference]
            anchored = anchored or kind in {'on', 'next_to'}
        elif 'reference' in row:
            raise ValueError('Unary placement relation cannot bind a reference')
        # Bind before invoking the native constructor: misspelled fields cannot
        # silently disappear or change the intended placement constraint.
        inspect.signature(classes[kind]).bind(**params)
        result.append(classes[kind](**params))
    if not anchored:
        raise ValueError('Risk obstacle requires an explicit positional task relation')
    return result


def static_relation_object(**kwargs):
    """Static USD object with a native reset writer, preserving static physics.

    Arena's generic writer assumes a RigidObject and fails for AssetBaseCfg.
    Only the single-environment task adapter is supported here. Static shapes
    remain static; no kinematic body or substitute collision mesh is created.
    """
    from isaaclab_arena.assets.object import Object
    class StaticRelationObject(Object):
        def write_scene_root_poses_to_sim(self,env,env_ids,poses):
            import numpy as np
            from pxr import Gf,UsdGeom,UsdPhysics,Usd
            ids=env_ids.detach().cpu().tolist()
            if env.num_envs!=1 or ids!=[0] or set(poses)!={self.get_scene_key()}:
                raise ValueError('Static relation writer requires one explicitly bound environment/root')
            values=poses[self.get_scene_key()].detach().cpu().numpy()
            if values.shape!=(1,7) or not np.isfinite(values).all():raise ValueError('Invalid static placement pose')
            row=values[0];q=row[3:7]
            if abs(float(q@q)-1)>1e-5:raise ValueError('Nonunit static placement quaternion')
            path=self.get_prim_path().replace('{ENV_REGEX_NS}','/World/envs/env_0')
            if any(x in path for x in '{}*'):raise ValueError('Unresolved static asset path')
            stage=env.sim.stage;prim=stage.GetPrimAtPath(path)
            if not prim:raise ValueError('Static asset root was not spawned')
            for child in Usd.PrimRange(prim):
                if child.HasAPI(UsdPhysics.RigidBodyAPI) and UsdPhysics.RigidBodyAPI(child).GetRigidBodyEnabledAttr().Get():
                    raise ValueError('Static reset writer cannot move an enabled rigid body')
            cache=UsdGeom.XformCache();old=np.asarray(cache.GetLocalToWorldTransform(prim)).T
            u,_,vt=np.linalg.svd(old[:3,:3]);rot=u@vt
            if np.linalg.det(rot)<0:u[:,-1]*=-1;rot=u@vt
            stretch=rot.T@old[:3,:3]
            world=np.asarray(Gf.Matrix4d().SetRotate(Gf.Quatd(float(q[3]),Gf.Vec3d(*map(float,q[:3]))))).T.copy()
            world[:3,:3]=world[:3,:3]@stretch
            world[:3,3]=row[:3]+env.scene.env_origins[0].detach().cpu().numpy()
            parent=np.asarray(cache.GetLocalToWorldTransform(prim.GetParent())).T
            xf=UsdGeom.Xformable(prim);xf.ClearXformOpOrder()
            name='xformOp:transform:taskStaticPlacement'
            op=UsdGeom.XformOp(prim.GetAttribute(name)) if prim.HasAttribute(name) else xf.AddTransformOp(opSuffix='taskStaticPlacement')
            xf.SetXformOpOrder([op]);op.Set(Gf.Matrix4d((np.linalg.inv(parent)@world).T.tolist()))
            actual=np.asarray(UsdGeom.XformCache().GetLocalToWorldTransform(prim)).T
            error=float(np.max(np.abs(actual-world)))
            if error>1e-7:raise ValueError('Static scene transform differs from sampled placement')
            records=getattr(env,'_risk_static_placement_writes',{})
            records[path]=dict(source='native sampled environment-local pose',pose_xyzw=row.tolist(),
                world_matrix=actual.tolist(),matrix_max_error=error,physics_representation='unchanged static USD collider',
                physics_steps_advanced_by_writer=0)
            env._risk_static_placement_writes=records
    return StaticRelationObject(**kwargs)
